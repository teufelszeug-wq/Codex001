"""Phase C evidence/coverage bridge; no fabricated discussions or training claims.

This validates supplied records, not the truth or entailment of their prose.
External evidence snapshots are self-reported until independently attested.
PR #4 owns presentation order; this module does not replace its meeting gate.
"""
from copy import deepcopy
from prism_engine.contracts import digest, fields, timestamp, numeric, validate

THEMES = {'DIAGNOSIS', 'COURSE', 'INFORMATION', 'CASE', 'BETS'}
STAGES = {'INITIAL', 'RESPONSE', 'FINAL', 'QUESTION', 'INTRO'}
FACILITATOR = 'SHINOMIYA_RITSU'
NEWCOMER = 'RIO'
BINDINGS = ('race_id', 'input_hash', 'prediction_hash')
RESULT_KEYS = {'results', 'result', 'settlement', 'payouts', 'winners', 'winner',
               'finish_position', 'win_payouts', 'refund_keys', 'target_result'}


def _result_fields(value):
    if isinstance(value, dict):
        return bool(set(value) & RESULT_KEYS) or any(_result_fields(v) for v in value.values())
    if isinstance(value, list):
        return any(_result_fields(v) for v in value)
    return False


def _sealed(value, key):
    if not isinstance(value, dict) or value.get(key) != digest({k: v for k, v in value.items() if k != key}):
        raise ValueError(key + ' mismatch')


def build_discussion_context(bundle, memory=None):
    """Extract a result-free PRE context from a sealed engine bundle.

    Pass settlement only to review_learning after PRE discussion validation.
    No speaker text is generated by this function.
    """
    fields(bundle, {'schema', 'prediction', 'market_values', 'normalization', 'raw',
                    'training_achievement_verified', 'production_deployed'},
           {'schema', 'prediction'})
    if bundle['schema'] != 'prism.engine.bundle/v1':
        raise ValueError('engine bundle schema required')
    p = bundle['prediction']; _sealed(p, 'lock_hash')
    if 'raw' in bundle and digest(validate(bundle['raw'])) != p['input_hash']:
        raise ValueError('raw/prediction mismatch')
    if p['mode'] not in {'SYNTHETIC', 'PRE_AVAILABLE', 'HISTORICAL_RECONSTRUCTION'}:
        raise ValueError('input temporal mode rejected')
    if timestamp(p['locked_at']) > timestamp(p['cutoff']):
        raise ValueError('prediction after cutoff')
    horses = p['features']['horses']
    if set(horses) != set(p['win']):
        raise ValueError('runner mismatch')
    if 'raw' in bundle:
        raw_horses = {r['horse_id']: r for r in bundle['raw']['runners']}
        if set(raw_horses) != set(horses):
            raise ValueError('raw/prediction runner set mismatch')
        for horse, observed in raw_horses.items():
            for field in ('horse_no', 'frame_no', 'barrier_no'):
                if horses[horse].get(field) != observed[field]:
                    raise ValueError('raw/prediction runner numbering mismatch')
            if p['frames'].get(horse) != str(observed['frame_no']):
                raise ValueError('raw/prediction frame map mismatch')
    roster = [{'horse_id': h, 'horse_no': f['horse_no'], 'frame_no': f['frame_no']}
              for h, f in sorted(horses.items(), key=lambda item: item[1]['horse_no'])]
    evidence = [{'evidence_id': 'engine:' + p['lock_hash'], 'kind': 'MODEL_OUTPUT',
                 'content': deepcopy(p), 'content_hash': digest(p),
                 'available_at': p['locked_at'], 'horse_ids': list(horses)}]
    market = bundle.get('market_values')
    if market is not None:
        if market['race_id'] != p['race_id'] or market['prediction_hash'] != p['lock_hash']:
            raise ValueError('market/prediction mismatch')
        # Legacy proposals with no observation timestamp are not citeable.
        if 'opened_at' in market:
            if not timestamp(p['locked_at']) <= timestamp(market['opened_at']) <= timestamp(p['cutoff']):
                raise ValueError('proposal availability')
            evidence.append({'evidence_id': 'proposal:' + digest(market), 'kind': 'MODEL_PROPOSAL',
                             'content': deepcopy(market), 'content_hash': digest(market),
                             'available_at': market['opened_at'], 'horse_ids': list(horses)})
    context = {'schema': 'prism.dialogue.context/v1', 'phase': 'PRE',
               'race_id': p['race_id'], 'input_hash': p['input_hash'], 'prediction_hash': p['lock_hash'],
               'input_mode': p['mode'], 'cutoff': p['cutoff'], 'locked_at': p['locked_at'],
               'roster': roster, 'win': deepcopy(p['win']), 'evidence': evidence,
               'facilitator': {'agent_id': FACILITATOR, 'name': '篠宮律', 'role': 'FACILITATOR'},
               'newcomer': {'agent_id': NEWCOMER, 'name': 'りお', 'role': 'NEWCOMER_QUESTIONER'},
               'source_authenticity_verified': False}
    if memory is not None:
        from prism_records.memory import verify_race_memory
        verify_race_memory(memory, race_id=p['race_id'], as_of=p['locked_at'])
        # DB horse IDs are source-scoped identities, not engine runner keys.
        # Match the whole race through explicit numbers and frames, never names.
        db_roster = memory['runners']
        numbered = {r['horse_no']: r for r in db_roster}
        if len(numbered) != len(db_roster) or len(db_roster) != len(roster):
            raise ValueError('memory roster coverage mismatch')
        horse_binding = {}
        for runner in roster:
            db_runner = numbered.get(runner['horse_no'])
            if db_runner is None or db_runner['frame_no'] != runner['frame_no']:
                raise ValueError('memory/prediction roster mismatch')
            horse_binding[runner['horse_id']] = db_runner['horse_id']
        context['records_memory'] = deepcopy(memory)
        context['memory_horse_map'] = horse_binding
        context['evidence'].append({'evidence_id': 'memory:' + memory['snapshot_hash'],
                                    'kind': 'PRE_SOURCE', 'content': deepcopy(memory),
                                    'content_hash': digest(memory), 'available_at': memory['as_of'],
                                    'horse_ids': [r['horse_id'] for r in roster]})
    context['context_hash'] = digest(context)
    return context


def validate_discussion(context, records):
    """Validate actual supplied records; no inference of prose quality or execution.

    Every required specialist must assess, answer another speaker, and conclude
    for each horse. Final judgments retain explicit invalidation conditions.
    Templates remain templates even if all structural fields are populated.
    """
    _sealed(context, 'context_hash')
    if context.get('phase') != 'PRE':
        raise ValueError('PRE context required')
    errors = []
    try:
        fields(records, {'schema', *BINDINGS, 'recorded_at', 'execution_mode', 'required_agents',
                         'evidence', 'turns', 'facilitator', 'newcomer', 'selections'},
               {'schema', *BINDINGS, 'recorded_at', 'execution_mode', 'required_agents',
                'evidence', 'turns', 'facilitator', 'newcomer'})
        if records['schema'] != 'prism.dialogue.records/v1': errors.append('SCHEMA')
        if any(records[k] != context[k] for k in BINDINGS): errors.append('BINDING')
        mode = records['execution_mode']
        if mode not in {'TEMPLATE', 'ROLE_SIMULATION', 'INDEPENDENT_EXECUTION'}: errors.append('MODE')
        recorded = timestamp(records['recorded_at'])
        if not timestamp(context['locked_at']) <= recorded <= timestamp(context['cutoff']):
            errors.append('PRE_TIME')
        if records['facilitator'] != FACILITATOR or records['newcomer'] != NEWCOMER:
            errors.append('ROLE_ASSIGNMENT')
        agents = records['required_agents']
        if (not isinstance(agents, list) or not agents or
            any(not isinstance(a, str) or not a.strip() or a in {FACILITATOR, NEWCOMER} for a in agents)
                or len(agents) != len(set(agents))): raise ValueError('required specialist roster')
        horses = {r['horse_id'] for r in context['roster']}
        evidence = {}
        for e in context['evidence'] + records['evidence']:
            fields(e, {'evidence_id', 'kind', 'content', 'content_hash', 'available_at', 'horse_ids'},
                   {'evidence_id', 'kind', 'content', 'content_hash', 'available_at', 'horse_ids'})
            if not isinstance(e['evidence_id'], str) or not e['evidence_id'].strip(): raise ValueError('evidence ID')
            if e['evidence_id'] in evidence: errors.append('DUPLICATE_EVIDENCE')
            if e['content_hash'] != digest(e['content']): errors.append('EVIDENCE_HASH')
            if e['kind'] not in {'MODEL_OUTPUT', 'MODEL_PROPOSAL', 'PRE_SOURCE'}: errors.append('RESULT_EVIDENCE_IN_PRE')
            if _result_fields(e['content']): errors.append('RESULT_FIELDS_IN_PRE')
            if timestamp(e['available_at']) > recorded: errors.append('FUTURE_EVIDENCE')
            if not e['horse_ids'] or not set(e['horse_ids']) <= horses: errors.append('EVIDENCE_HORSES')
            evidence[e['evidence_id']] = e
        seen = {}; coverage = {}; themes = set(); texts = set(); challenges = 0; minority = 0
        questions = 0; introductions = 0; rio_finals = 0
        for t in records['turns']:
            fields(t, {'turn_id', 'agent_id', 'horse_id', 'theme', 'stage', 'text', 'evidence_refs',
                       'responds_to', 'stance', 'invalidation_condition'},
                   {'turn_id', 'agent_id', 'horse_id', 'theme', 'stage', 'text', 'evidence_refs',
                    'responds_to', 'stance', 'invalidation_condition'})
            tid = t['turn_id']; agent = t['agent_id']; horse = t['horse_id']; stage = t['stage']
            if not isinstance(tid, str) or not tid.strip() or tid in seen: errors.append('DUPLICATE_OR_EMPTY_TURN')
            if agent not in set(agents) | {FACILITATOR, NEWCOMER}: errors.append('UNKNOWN_AGENT')
            if horse not in horses and not (stage == 'INTRO' and horse is None): errors.append('UNKNOWN_HORSE')
            if stage not in STAGES or t['theme'] not in THEMES: errors.append('STAGE_OR_THEME')
            themes.add(t['theme'])
            if not isinstance(t['text'], str) or not t['text'].strip(): errors.append('EMPTY_TEXT')
            normalized = ''.join(t['text'].split())
            if normalized in texts: errors.append('DUPLICATE_TEXT')
            texts.add(normalized)
            if not isinstance(t['evidence_refs'], list) or not t['evidence_refs']: errors.append('MISSING_EVIDENCE')
            for ref in t['evidence_refs']:
                if ref not in evidence: errors.append('BROKEN_EVIDENCE_REF')
                elif horse is not None and horse not in evidence[ref]['horse_ids']: errors.append('UNRELATED_HORSE_EVIDENCE')
            reply = t['responds_to']
            if stage in {'RESPONSE', 'QUESTION'}:
                target = seen.get(reply)
                if target is None or target['agent_id'] == agent or target['horse_id'] != horse:
                    errors.append('BROKEN_RESPONSE')
                if t['stance'] not in {'CHALLENGE', 'SUPPORT', 'MINORITY', 'QUESTION'}: errors.append('MISSING_RESPONSE_REASON_KIND')
            elif reply is not None: errors.append('UNEXPECTED_RESPONSE_REF')
            if agent == NEWCOMER:
                if stage == 'QUESTION': questions += 1
                elif stage == 'FINAL':
                    rio_finals += 1
                    question_ids = {key for key, x in seen.items() if x['agent_id'] == NEWCOMER and x['stage'] == 'QUESTION' and x['horse_id'] == horse}
                    if not question_ids:
                        errors.append('RIO_FINAL_WITHOUT_QUESTION')
                    elif not any(x['agent_id'] in agents and x['stage'] == 'RESPONSE' and x['responds_to'] in question_ids for x in seen.values()):
                        errors.append('RIO_QUESTION_UNANSWERED')
                    if not isinstance(t['invalidation_condition'], str) or not t['invalidation_condition'].strip():
                        errors.append('MISSING_INVALIDATION_CONDITION')
                else: errors.append('RIO_ROLE')
            if stage == 'INTRO' and agent == FACILITATOR: introductions += 1
            if stage in {'INITIAL', 'RESPONSE', 'FINAL'} and agent in agents:
                key = (agent, horse); history = coverage.setdefault(key, [])
                if stage == 'RESPONSE' and 'INITIAL' not in history: errors.append('RESPONSE_BEFORE_INITIAL')
                if stage == 'FINAL' and 'RESPONSE' not in history: errors.append('FINAL_BEFORE_RESPONSE')
                if stage in {'INITIAL', 'FINAL'} and stage in history: errors.append('DUPLICATE_JUDGMENT')
                history.append(stage)
                if stage == 'FINAL' and (not isinstance(t['invalidation_condition'], str) or not t['invalidation_condition'].strip()):
                    errors.append('MISSING_INVALIDATION_CONDITION')
            if stage == 'RESPONSE' and t['stance'] == 'CHALLENGE': challenges += 1
            if stage == 'RESPONSE' and t['stance'] == 'MINORITY': minority += 1
            seen[tid] = t
        if themes != THEMES: errors.append('FIVE_THEMES_REQUIRED')
        if not introductions or not questions or not rio_finals: errors.append('FACILITATION_OR_RIO_QUESTION_MISSING')
        if not challenges or not minority: errors.append('CHALLENGE_OR_MINORITY_MISSING')
        if any(not {'INITIAL', 'RESPONSE', 'FINAL'} <= set(coverage.get((a, h), [])) for a in agents for h in horses):
            errors.append('ALL_AGENT_ALL_HORSE_COVERAGE')
        selections = records.get('selections', [])
        if not isinstance(selections, list): raise ValueError('selection list required')
        selected_pairs = set(); top_pickers = set()
        for selection in selections:
            fields(selection, {'agent_id', 'horse_id', 'selection', 'turn_id'},
                   {'agent_id', 'horse_id', 'selection', 'turn_id'})
            pair = (selection['agent_id'], selection['horse_id'])
            if pair in selected_pairs: errors.append('DUPLICATE_SELECTION')
            selected_pairs.add(pair)
            if selection['selection'] not in {'TOP_PICK', 'CONTENDER', 'WATCH', 'AVOID'}:
                errors.append('INVALID_SELECTION')
            turn = seen.get(selection['turn_id'])
            if (turn is None or turn['stage'] != 'FINAL' or
                (turn['agent_id'], turn['horse_id']) != pair): errors.append('SELECTION_FINAL_BINDING')
            if selection['selection'] == 'TOP_PICK':
                if selection['agent_id'] in top_pickers: errors.append('MULTIPLE_TOP_PICKS')
                top_pickers.add(selection['agent_id'])
    except (KeyError, TypeError, ValueError, AttributeError):
        errors.append('MALFORMED_RECORD')
    valid = not errors
    # Logged counts describe supplied text. None is an attested learning count.
    turns = records.get('turns', []) if isinstance(records, dict) else []
    safe_turns = [t for t in turns if isinstance(t, dict)] if isinstance(turns, list) else []
    return {'schema': 'prism.dialogue.audit/v1', **{k: context[k] for k in BINDINGS},
            'records_hash': digest(records), 'context_hash': context['context_hash'],
            'status': 'STRUCTURAL_PASS' if valid else 'FAIL', 'errors': sorted(set(errors)),
            'counts': {'submitted_turns': len(safe_turns),
                       'submitted_characters': sum(len(t.get('text', '')) for t in safe_turns if isinstance(t.get('text'), str)),
                       'verified_independent_sessions': 0, 'verified_training_updates': 0},
            'execution_mode': records.get('execution_mode') if isinstance(records, dict) else None,
            'independent_execution_verified': False, 'training_achievement_verified': False,
            'source_authenticity_verified': False, 'semantic_evidence_reviewed': False,
            'note': 'Structural validation only; no external source, prose-quality, or independent-execution attestation.'}


def review_learning(context, records, result):
    """Record a post-race error for review. Never updates model parameters."""
    audit = validate_discussion(context, records)
    if audit['status'] != 'STRUCTURAL_PASS': raise ValueError('discussion must pass before review')
    fields(result, {'race_id', 'prediction_hash', 'available_at', 'winners', 'content_hash'},
           {'race_id', 'prediction_hash', 'available_at', 'winners', 'content_hash'})
    _sealed(result, 'content_hash')
    if result['race_id'] != context['race_id'] or result['prediction_hash'] != context['prediction_hash']:
        raise ValueError('result/prediction mismatch')
    if timestamp(result['available_at']) <= timestamp(context['cutoff']): raise ValueError('result before race cutoff')
    winners = result['winners']; probs = context['win']
    if not winners or len(winners) != len(set(winners)) or not set(winners) <= set(probs):
        raise ValueError('winner identities')
    for p in probs.values(): numeric(p, 0, 1)
    brier = sum((p - (1 / len(winners) if h in winners else 0)) ** 2 for h, p in probs.items())
    out = {'schema': 'prism.dialogue.learning-review/v1', **{k: context[k] for k in BINDINGS},
           'records_hash': audit['records_hash'], 'result_hash': result['content_hash'],
           'available_at': result['available_at'], 'brier_sum': brier,
           'status': 'REVIEW_RECORDED_NOT_TRAINED', 'input_mode': context['input_mode'],
           'forward_performance_verified': False, 'training_achievement_verified': False,
           'model_parameters_changed': False}
    out['review_hash'] = digest(out)
    return out
